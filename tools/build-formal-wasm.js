#!/usr/bin/env node
// Builds the Lean core (formal/) to WebAssembly: src/engine/lean/exegra-lean.{mjs,wasm} (generated,
// not committed). Node-only. `npm run build:formal-wasm`.
//
//   node tools/build-formal-wasm.js [--jobs N]
//
// The module is the C that Lean's own compiler emits, compiled with emscripten and linked with
// Lean's C++ runtime: the same C the native `exegra-lean` is compiled from. Its one entry point is
// Exegra.Api (formal/Exegra/Api.lean), bound in JS by src/core/lean.js.
//
// Inputs, all pinned (PINS below) and checked:
//   - the Lean toolchain of formal/lean-toolchain (installed by elan); `lake build` emits the C of
//     every Exegra module, and the toolchain's `lean -c` emits the C of the Init/Std modules that
//     Exegra.Api imports, from the sources the toolchain ships;
//   - the Lean runtime sources (src/runtime, src/include) of the lean4 repository at the toolchain's
//     tag, verified by commit, with formal/wasm/patches/*.patch applied;
//   - libuv at the version Lean's own wasm build pinned, verified by commit;
//   - emscripten (emsdk at a pinned commit, SDK version pinned).
//
// The target is wasm64 (-sMEMORY64=1) only: pointers are 8 bytes, so the C generated by the 64-bit
// compiler runs under exactly the assumptions it was generated for (a wasm32 build would need C from a
// 32-bit compiler; spike/lean-wasm/README.md, "wasm32 caveats"). Memory64 runs in Node 24, Chrome 133+
// and Firefox 134+; stable Safari does not support it yet, so Exegra does not run there until it does.
//
// Downloads and checkout-independent build products (emsdk, sources, the Init/Std C, the objects of
// the runtime, libuv and Init/Std) live in a cache shared by all checkouts:
//   EXEGRA_CACHE_DIR, else %LOCALAPPDATA%\exegra\cache\formal-wasm (Windows),
//   else $XDG_CACHE_HOME/exegra/formal-wasm, else ~/.cache/exegra/formal-wasm.
// Each entry's directory name carries its pinned version or a hash of what it was built from, so a
// changed pin or flag never reuses a stale entry. EMSDK=<emsdk checkout> uses an existing emsdk instead
// (its emscripten version must equal the pin). The Exegra objects live in formal/.lake/wasm/.
//
// Parallelism: --jobs N or EXEGRA_BUILD_JOBS, default 3 (each `lean -c` of a large stdlib module and
// each emcc of a large C file can take about 1 GB).
//
// Needs: git, Node, elan with the toolchain of formal/lean-toolchain, network access for the first
// build (Python only if emsdk has to be installed). No CMake.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawn, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FORMAL = path.join(ROOT, 'formal');
const WASM_SRC = path.join(FORMAL, 'wasm');
const ENTRY_MODULE = 'Exegra.Api';

/** Every pinned input. A Lean toolchain upgrade adds its runtime commit here. */
const PINS = {
  emsdk: { repo: 'https://github.com/emscripten-core/emsdk.git', commit: '708dcbcc9ee23bc7d2dad44fc90db377e38b771c', version: '7.0.0' },
  lean4: {
    repo: 'https://github.com/leanprover/lean4.git',
    /** toolchain version -> commit of its tag */
    commits: /** @type {Record<string, string>} */ ({ '4.35.0': 'eb6cafb7290e8bd5f2937522d8d804f58f02bafc' }),
  },
  libuv: { repo: 'https://github.com/libuv/libuv.git', tag: 'v1.48.0', commit: 'e9f29cb984231524e3931aa0ae2c5dae1a32884e' },
};

/** The libuv sources an emscripten build compiles: libuv's CMake lists for a non-Linux unix, plus
 * src/unix/no-proctitle.c, which Lean's own wasm build adds (it patches libuv's CMakeLists.txt). */
const LIBUV_SOURCES = [
  'fs-poll', 'idna', 'inet', 'random', 'strscpy', 'strtok', 'thread-common', 'threadpool', 'timer', 'uv-common',
  'uv-data-getter-setters', 'version', 'unix/async', 'unix/core', 'unix/dl', 'unix/fs', 'unix/getaddrinfo',
  'unix/getnameinfo', 'unix/loop-watcher', 'unix/loop', 'unix/no-proctitle', 'unix/pipe', 'unix/poll', 'unix/process',
  'unix/random-devurandom', 'unix/signal', 'unix/stream', 'unix/tcp', 'unix/thread', 'unix/tty', 'unix/udp',
];

/** The runtime sources of lean4/src/runtime that a single-threaded build without GMP and mimalloc needs. */
const RUNTIME_SOURCES = [
  'debug', 'thread', 'mpz', 'utf8', 'object', 'apply', 'exception', 'interrupt', 'memory', 'stackinfo', 'compact',
  'init_module', 'io', 'hash', 'byteslice', 'platform', 'alloc', 'allocprof', 'sharecommon', 'stack_overflow', 'process',
  'object_ref', 'mpn', 'mutex', 'libuv', 'uv/net_addr', 'uv/event_loop', 'uv/timer', 'uv/tcp', 'uv/udp', 'uv/dns',
  'uv/system', 'uv/signal', 'openssl',
];

const EXPORTS = ['_exegra_init', '_exegra_request', '_exegra_reply_ptr', '_exegra_reply_len', '_exegra_pointer_size', '_malloc', '_free'];

const isWin = process.platform === 'win32';

/** @param {string} msg @returns {never} */
function fail(msg) {
  process.stderr.write(`build:formal-wasm: ${msg}\n`);
  process.exit(1);
}
/** @param {string} msg */
const log = (msg) => process.stdout.write(`build:formal-wasm: ${msg}\n`);
/** @param {string|Buffer} s */
const sha = (s) => crypto.createHash('sha256').update(s).digest('hex');
/** @param {string} p */
const exists = (p) => fs.existsSync(p);

/**
 * @param {string} cmd @param {string[]} args
 * @param {import('node:child_process').SpawnSyncOptions & {quiet?: boolean}} [opts]
 */
function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { stdio: opts.quiet ? 'pipe' : 'inherit', encoding: 'utf8', windowsHide: true, ...opts });
  if (r.error) fail(`could not run ${cmd}: ${r.error.message}`);
  if (r.status !== 0) fail(`${cmd} ${args.join(' ')} exited with status ${r.status}${opts.quiet ? `\n${r.stdout ?? ''}${r.stderr ?? ''}` : ''}`);
  return String(r.stdout ?? '');
}

/** @param {string} cmd @param {string[]} args @param {import('node:child_process').SpawnOptions} opts */
function runAsync(cmd, args, opts) {
  return new Promise((resolve, reject) => {
    const child = spawn(cmd, args, { stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true, ...opts });
    let out = '';
    child.stdout?.on('data', (d) => { out += d; });
    child.stderr?.on('data', (d) => { out += d; });
    child.on('error', reject);
    child.on('close', (code) => (code === 0 ? resolve(out) : reject(new Error(`${path.basename(cmd)} ${args.slice(-3).join(' ')} exited with status ${code}\n${out.slice(-3000)}`))));
  });
}

/** Run `tasks` with at most `jobs` at a time. @param {(() => Promise<unknown>)[]} tasks @param {number} jobs */
async function pool(tasks, jobs) {
  let next = 0;
  const worker = async () => {
    while (next < tasks.length) await tasks[next++]();
  };
  await Promise.all(Array.from({ length: Math.min(jobs, tasks.length) }, worker));
}

function cacheRoot() {
  if (process.env.EXEGRA_CACHE_DIR) return path.resolve(process.env.EXEGRA_CACHE_DIR);
  if (isWin && process.env.LOCALAPPDATA) return path.join(process.env.LOCALAPPDATA, 'exegra', 'cache', 'formal-wasm');
  const base = process.env.XDG_CACHE_HOME || path.join(os.homedir(), '.cache');
  return path.join(base, 'exegra', 'formal-wasm');
}

/** Write to a temporary sibling and rename, so an interrupted build never leaves a half entry. @param {string} p @param {string|Buffer} data */
function writeAtomic(p, data) {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  const tmp = `${p}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, data);
  fs.renameSync(tmp, p);
}

