/** A git checkout of `repo` at `ref`, verified to be at `commit`. @param {string} dir @param {string} repo @param {string} ref @param {string} commit @param {string[]} [sparse] */
function gitCheckout(dir, repo, ref, commit, sparse) {
  const marker = path.join(dir, '.exegra-verified');
  if (exists(marker)) return;
  const tmp = `${dir}.partial`;
  fs.rmSync(tmp, { recursive: true, force: true });
  fs.mkdirSync(tmp, { recursive: true });
  const git = (/** @type {string[]} */ ...args) => run('git', ['-C', tmp, ...args], { quiet: true });
  log(`fetching ${repo} ${ref}`);
  git('init', '-q');
  git('remote', 'add', 'origin', repo);
  if (sparse) {
    git('config', 'core.sparseCheckout', 'true');
    git('sparse-checkout', 'set', '--no-cone', ...sparse);
  }
  git('fetch', '-q', '--depth', '1', ...(sparse ? ['--filter=blob:none'] : []), 'origin', ref);
  git('checkout', '-q', 'FETCH_HEAD');
  const head = git('rev-parse', 'HEAD').trim();
  if (head !== commit) fail(`${repo} ${ref} is at ${head}, but the pin is ${commit}`);
  fs.renameSync(tmp, dir);
  fs.writeFileSync(marker, `${commit}\n`);
}

/** The emsdk to use: EMSDK, or the pinned one in the cache (installed on first use). @param {string} cache */
function emsdk(cache) {
  const want = PINS.emsdk.version;
  const dir = process.env.EMSDK ? path.resolve(process.env.EMSDK) : path.join(cache, `emsdk-${want}`);
  const versionFile = path.join(dir, 'upstream', 'emscripten', 'emscripten-version.txt');
  if (!exists(versionFile)) {
    if (process.env.EMSDK) fail(`EMSDK=${dir} has no upstream/emscripten (install and activate ${want} there)`);
    gitCheckout(dir, PINS.emsdk.repo, PINS.emsdk.commit, PINS.emsdk.commit);
    const tool = isWin ? path.join(dir, 'emsdk.bat') : path.join(dir, 'emsdk');
    log(`installing emscripten ${want} (a large download)`);
    run(tool, ['install', want], { cwd: dir, shell: isWin });
    run(tool, ['activate', want], { cwd: dir, shell: isWin });
  }
  const have = fs.readFileSync(versionFile, 'utf8').trim().replace(/"/g, '');
  if (have !== want) fail(`emscripten ${have} found in ${dir}, but the pin is ${want}`);
  const bin = path.join(dir, 'upstream', 'emscripten');
  /** @type {NodeJS.ProcessEnv} */
  const env = { ...process.env, EM_CONFIG: path.join(dir, '.emscripten'), EMSDK: dir };
  const py = path.join(dir, 'python');
  if (exists(py)) {
    const v = fs.readdirSync(py)[0];
    if (v) env.EMSDK_PYTHON = path.join(py, v, isWin ? 'python.exe' : 'bin/python3');
  }
  const exe = (/** @type {string} */ n) => path.join(bin, isWin ? `${n}.exe` : n);
  return { dir, version: have, env, emcc: exe('emcc'), emxx: exe('em++'), emar: exe('emar') };
}

/** The Lean toolchain of formal/: its version and sysroot. */
function toolchain() {
  const r = spawnSync('lean', ['--print-prefix'], { cwd: FORMAL, encoding: 'utf8', windowsHide: true });
  if (r.error || r.status !== 0) fail('`lean` is not on the PATH (install elan; formal/lean-toolchain pins the toolchain)');
  const prefix = String(r.stdout).trim();
  const v = spawnSync(path.join(prefix, 'bin', 'lean'), ['--version'], { encoding: 'utf8', windowsHide: true });
  const version = /version ([0-9]+\.[0-9]+\.[0-9]+)/.exec(String(v.stdout))?.[1];
  if (!version) fail(`could not read the version of ${prefix}`);
  return { prefix, version: /** @type {string} */ (version), lean: path.join(prefix, 'bin', isWin ? 'lean.exe' : 'lean') };
}

// ---------------------------------------------------------------------------
// The modules: the import closure of Exegra.Api
// ---------------------------------------------------------------------------

const IMPORT = /^\s*(?:public\s+)?(?:meta\s+)?import\s+(?:all\s+)?([A-Za-z0-9_.]+)/gm;

/** Every module in the import closure of `root`, looked up in formal/ then in the toolchain's sources.
 * Every module imports Init implicitly unless it starts with `prelude`. @param {string} root @param {string} stdSrc */
function importClosure(root, stdSrc) {
  /** @param {string} mod */
  const find = (mod) => {
    for (const base of [FORMAL, stdSrc]) {
      const p = path.join(base, ...mod.split('.')) + '.lean';
      if (exists(p)) return p;
    }
    return fail(`module not found: ${mod}`);
  };
  const seen = new Set();
  const todo = [root];
  while (todo.length) {
    const mod = /** @type {string} */ (todo.pop());
    if (seen.has(mod)) continue;
    seen.add(mod);
    const text = fs.readFileSync(find(mod), 'utf8').replace(/\/-[\s\S]*?-\//g, '').replace(/--[^\n]*/g, '');
    const header = text.split(/\n(?:namespace|section|open|def|theorem|structure|inductive)\b/, 1)[0];
    const imports = [...header.matchAll(IMPORT)].map((m) => m[1]);
    if (!/^\s*prelude\b/m.test(header)) imports.push('Init');
    todo.push(...imports);
  }
  return [...seen].sort();
}

// ---------------------------------------------------------------------------
// Build steps
// ---------------------------------------------------------------------------

/** Compile `src` to `obj` unless `obj` exists with the same key. @param {{emcc: string, env: NodeJS.ProcessEnv}} em @param {string} compiler @param {string[]} flags @param {string} src @param {string} obj @param {string} key */
function compileTask(em, compiler, flags, src, obj, key) {
  const stamp = `${obj}.key`;
  if (exists(obj) && exists(stamp) && fs.readFileSync(stamp, 'utf8') === key) return null;
  return async () => {
    fs.mkdirSync(path.dirname(obj), { recursive: true });
    const tmp = `${obj}.${process.pid}.tmp.o`;
    await runAsync(compiler, [...flags, '-c', src, '-o', tmp], { env: em.env, shell: false });
    fs.renameSync(tmp, obj);
    fs.writeFileSync(stamp, key);
  };
}

async function main() {
  const argv = process.argv.slice(2);
  const ji = argv.indexOf('--jobs');
  const jobs = Math.max(1, Number(ji >= 0 ? argv[ji + 1] : process.env.EXEGRA_BUILD_JOBS ?? 3) || 3);
  const variant = 'wasm64';
  const outDir = path.join(ROOT, 'src', 'engine', 'lean');
  const started = Date.now();

  const tc = toolchain();
  const pinned = (fs.readFileSync(path.join(FORMAL, 'lean-toolchain'), 'utf8').trim().match(/v([0-9.]+)$/) ?? [])[1];
  if (pinned !== tc.version) fail(`formal/lean-toolchain pins ${pinned}, but \`lean\` in formal/ is ${tc.version}`);
  const leanCommit = PINS.lean4.commits[tc.version];
  if (!leanCommit) fail(`no runtime commit pinned for Lean ${tc.version}: add the commit of tag v${tc.version} to PINS.lean4.commits`);

  const cache = cacheRoot();
  fs.mkdirSync(cache, { recursive: true });
  log(`cache ${cache}; ${variant}; ${jobs} jobs`);
  const em = emsdk(cache);

  // Lean runtime sources at the toolchain's tag, patched.
  const patches = fs.readdirSync(path.join(WASM_SRC, 'patches')).filter((f) => f.endsWith('.patch')).sort();
  const patchText = patches.map((f) => fs.readFileSync(path.join(WASM_SRC, 'patches', f), 'utf8').replace(/\r\n/g, '\n')).join('\n');
  const lean4 = path.join(cache, `lean4-v${tc.version}-${sha(patchText).slice(0, 12)}`);
  if (!exists(path.join(lean4, '.exegra-patches'))) {
    fs.rmSync(lean4, { recursive: true, force: true });
    gitCheckout(lean4, PINS.lean4.repo, `refs/tags/v${tc.version}`, leanCommit, ['/src/runtime/', '/src/include/', '/src/util/']);
    for (const f of patches) run('git', ['-C', lean4, 'apply', '--whitespace=nowarn', path.join(WASM_SRC, 'patches', f)], { quiet: true });
    fs.writeFileSync(path.join(lean4, '.exegra-patches'), patches.join('\n'));
  }
  const uv = path.join(cache, `libuv-${PINS.libuv.tag}`);
  gitCheckout(uv, PINS.libuv.repo, `refs/tags/${PINS.libuv.tag}`, PINS.libuv.commit);

  // formal/ itself: lake emits the C of every Exegra module.
  log('lake build');
  run('lake', ['build'], { cwd: FORMAL, quiet: true });
  const modules = importClosure(ENTRY_MODULE, path.join(tc.prefix, 'src', 'lean'));
  const stdMods = modules.filter((m) => /^(Init|Std)\b/.test(m));
  const exegraMods = modules.filter((m) => m === 'Exegra' || m.startsWith('Exegra.'));
  const other = modules.filter((m) => !stdMods.includes(m) && !exegraMods.includes(m));
  if (other.length) fail(`${ENTRY_MODULE} imports modules outside Init, Std and Exegra: ${other.join(', ')} (their C is not generated)`);

  // Init/Std C from the toolchain's own `lean -c` (the toolchain's .olean files serve the imports).
  const stdC = path.join(cache, `stdlib-c-v${tc.version}`);
  fs.mkdirSync(stdC, { recursive: true });
  const missing = stdMods.filter((m) => !exists(path.join(stdC, `${m}.c`)));
  if (missing.length) {
    log(`generating C for ${missing.length} of ${stdMods.length} Init/Std modules with lean -c`);
    const env = { ...process.env, LEAN_PATH: path.join(tc.prefix, 'lib', 'lean') };
    const srcRoot = path.join(tc.prefix, 'src', 'lean');
    await pool(missing.map((m) => async () => {
      const tmp = path.join(stdC, `${m}.${process.pid}.tmp`);
      await runAsync(tc.lean, ['--root=.', '-c', tmp, path.join(...m.split('.')) + '.lean'], { cwd: srcRoot, env });
      fs.renameSync(tmp, path.join(stdC, `${m}.c`));
    }), jobs);
  }

  // Compiler flags. lean.h lays out the 8-byte scalar fields of static objects as two 4-byte words
  // under LEAN_EMSCRIPTEN, which is wrong for wasm64: the generated C is compiled without it, with the
  // 64-bit layout it was generated for. The runtime needs it (its emscripten platform layer).
  const mem = ['-sMEMORY64=1'];
  const common = ['-O3', '-DNDEBUG', '-fwasm-exceptions', '-ffp-contract=off', '-Wno-deprecated', ...mem];
  const genDir = path.join(cache, `lean-config-v${tc.version}-${variant}`);
  const [maj, min, pat] = tc.version.split('.');
  writeIfChanged(path.join(genDir, 'lean', 'config.h'), '#pragma once\n#include <lean/version.h>\n#define LEAN_IS_STAGE0 0\n');
  writeIfChanged(path.join(genDir, 'lean', 'version.h'), `#pragma once\n#define LEAN_VERSION_MAJOR ${maj}\n#define LEAN_VERSION_MINOR ${min}\n#define LEAN_VERSION_PATCH ${pat}\n#define LEAN_VERSION_IS_RELEASE 1\n#define LEAN_SPECIAL_VERSION_DESC ""\n#define LEAN_VERSION_STRING "${tc.version}"\n#define LEAN_PLATFORM_TARGET "${variant}-unknown-emscripten"\n#define LEAN_MANUAL_ROOT "https://lean-lang.org/doc/reference/${tc.version}/"\n`);
  writeIfChanged(path.join(genDir, 'githash.h'), '#define LEAN_GITHASH ""\n');
  const cFlags = [...common, '-Wno-unused-parameter', '-Wno-unused-label', `-I${genDir}`, `-I${path.join(lean4, 'src', 'include')}`];
  // runtime/thread.h names std::adopt_lock_t in its single-threaded branch without including <mutex>.
  const rtFlags = ['-std=c++20', ...common, '-DLEAN_EMSCRIPTEN', `-I${genDir}`, `-I${path.join(lean4, 'src')}`, `-I${path.join(lean4, 'src', 'include')}`, `-I${path.join(uv, 'include')}`, '-include', 'mutex'];
  const uvFlags = ['-std=gnu90', ...common, '-fvisibility=hidden', '-fno-strict-aliasing', '-D_FILE_OFFSET_BITS=64', '-D_LARGEFILE_SOURCE', '-w', `-I${path.join(uv, 'include')}`, `-I${path.join(uv, 'src')}`];

  const objKey = (/** @type {string[]} */ flags) => sha(JSON.stringify([em.version, flags.map((f) => f.replace(cache, '<cache>'))])).slice(0, 12);
  const rtObj = path.join(cache, `obj-runtime-${path.basename(lean4)}-${variant}-${objKey(rtFlags)}`);
  const uvObj = path.join(cache, `obj-libuv-${PINS.libuv.tag}-${variant}-${objKey(uvFlags)}`);
  const stdObj = path.join(cache, `obj-stdlib-v${tc.version}-${variant}-${objKey(cFlags)}`);
  const exObj = path.join(FORMAL, '.lake', 'wasm', variant);

  /** @type {(() => Promise<void>)[]} */
  const tasks = [];
  /** @type {string[]} */
  const objects = [];
  const add = (/** @type {string} */ compiler, /** @type {string[]} */ flags, /** @type {string} */ src, /** @type {string} */ obj, /** @type {string} */ key) => {
    objects.push(obj);
    const t = compileTask(em, compiler, flags, src, obj, key);
    if (t) tasks.push(t);
  };
  for (const s of RUNTIME_SOURCES) add(em.emxx, rtFlags, path.join(lean4, 'src', 'runtime', `${s}.cpp`), path.join(rtObj, `${s.replace('/', '_')}.o`), 'v1');
  for (const s of LIBUV_SOURCES) add(em.emcc, uvFlags, path.join(uv, 'src', `${s}.c`), path.join(uvObj, `${s.replace('/', '_')}.o`), 'v1');
  for (const m of stdMods) add(em.emcc, cFlags, path.join(stdC, `${m}.c`), path.join(stdObj, `${m}.o`), 'v1');
  const irDir = path.join(FORMAL, '.lake', 'build', 'ir');
  const flagKey = objKey(cFlags);
  for (const m of exegraMods) {
    const src = path.join(irDir, ...m.split('.')) + '.c';
    if (!exists(src)) fail(`lake build did not emit ${path.relative(ROOT, src)}`);
    add(em.emcc, cFlags, src, path.join(exObj, 'obj', `${m}.o`), `${flagKey} ${sha(fs.readFileSync(src))}`);
  }
  const glue = path.join(WASM_SRC, 'glue.c');
  add(em.emcc, cFlags, glue, path.join(exObj, 'obj', 'glue.o'), `${flagKey} ${sha(fs.readFileSync(glue))}`);

  if (tasks.length) {
    log(`compiling ${tasks.length} of ${objects.length} C/C++ files with emscripten ${em.version}`);
    await pool(tasks, jobs);
  }

  // Link. The JS glue is built for the web environment with synchronous instantiation: src/core/lean.js
  // hands it the module bytes (`wasmBinary`), read with node:fs in Node and fetched in the browser,
  // so loading is synchronous in Node (as the engine facade needs) and needs no Node code in the glue.
  const linkFlags = [
    '-O3', '-fwasm-exceptions', ...mem, '-sALLOW_MEMORY_GROWTH=1', '-sSTACK_SIZE=8MB', '-sMODULARIZE=1', '-sEXPORT_ES6=1',
    '-sENVIRONMENT=web,worker', '-sWASM_ASYNC_COMPILATION=0', `-sEXPORTED_FUNCTIONS=${EXPORTS.join(',')}`,
    '-sEXPORTED_RUNTIME_METHODS=HEAPU8', '-Wno-deprecated',
  ];
  const objHashes = objects.map((o) => fs.readFileSync(`${o}.key`, 'utf8') + path.basename(o));
  const linkKey = sha(JSON.stringify([em.version, linkFlags, objHashes, objects.map((o) => fs.statSync(o).size)]));
  const infoPath = path.join(outDir, 'build-info.json');
  /** @type {any} */
  let prior = null;
  try { prior = JSON.parse(fs.readFileSync(infoPath, 'utf8')); } catch { /* not built yet */ }
  if (prior?.linkKey === linkKey && exists(path.join(outDir, 'exegra-lean.wasm')) && exists(path.join(outDir, 'exegra-lean.mjs'))) {
    writeTypes(outDir);
    log(`${path.relative(ROOT, outDir).replace(/\\/g, '/')} is up to date`);
    return;
  }
  const stage = path.join(exObj, 'link');
  fs.rmSync(stage, { recursive: true, force: true });
  fs.mkdirSync(stage, { recursive: true });
  // The object list is too long for one Windows command line: pass it in a response file.
  const rsp = path.join(stage, 'objects.rsp');
  fs.writeFileSync(rsp, objects.map((o) => `"${o.replace(/\\/g, '/')}"`).join('\n'));
  log(`linking ${objects.length} objects`);
  // wasm-ld warns that lean_io_create_tempfile/tempdir differ in signature between Init and the
  // runtime (lean4#16090, fixed after v4.35.0); neither is reachable from Exegra.Api.
  await runAsync(em.emxx, [...linkFlags, `@${rsp}`, '-o', path.join(stage, 'exegra-lean.mjs')], { env: em.env });

  fs.mkdirSync(outDir, { recursive: true });
  for (const f of ['exegra-lean.mjs', 'exegra-lean.wasm']) fs.copyFileSync(path.join(stage, f), path.join(outDir, f));
  writeTypes(outDir);
  const wasmBytes = fs.readFileSync(path.join(outDir, 'exegra-lean.wasm'));
  const info = {
    variant, entry: ENTRY_MODULE, lean: tc.version, leanRuntimeCommit: leanCommit, patches,
    emscripten: em.version, emsdkCommit: PINS.emsdk.commit, libuv: `${PINS.libuv.tag} ${PINS.libuv.commit}`,
    modules: { stdlib: stdMods.length, exegra: exegraMods },
    wasmBytes: wasmBytes.length, wasmSha256: sha(wasmBytes), linkKey,
  };
  writeAtomic(infoPath, `${JSON.stringify(info, null, 2)}\n`);
  log(`wrote ${path.relative(ROOT, outDir).replace(/\\/g, '/')} (${wasmBytes.length} bytes of wasm) in ${((Date.now() - started) / 1000).toFixed(1)} s`);
}

/** The type of the generated loader, so that type checking does not descend into emscripten's JS. @param {string} outDir */
function writeTypes(outDir) {
  writeIfChanged(path.join(outDir, 'exegra-lean.d.mts'), [
    '/** The emscripten module factory: the module is ready when it returns (synchronous instantiation). */',
    'declare const factory: (module: Record<string, any>) => Promise<any>;',
    'export default factory;',
    '',
  ].join('\n'));
}

/** @param {string} p @param {string} text */
function writeIfChanged(p, text) {
  try { if (fs.readFileSync(p, 'utf8') === text) return; } catch { /* absent */ }
  writeAtomic(p, text);
}

