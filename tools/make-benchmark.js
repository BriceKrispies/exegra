#!/usr/bin/env node
// Generates specs/benchmark/spec.jsonc: a synthetic specification with several
// hundred components and relationships, used to measure renderer and layout
// behaviour. Deterministic (fixed-seed generator), so the file is reproducible.
// Usage: node tools/make-benchmark.js [subsystems] [componentsPerSubsystem]

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { analyzeSpec } from '../src/core/analyze.js';

const groups = Number(process.argv[2] ?? 12);
const perGroup = Number(process.argv[3] ?? 32);

let seed = 20261114;
const rand = () => {
  // Linear congruential generator: reproducible, no Math.random.
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return seed / 4294967296;
};
const pick = (/** @type {any[]} */ list) => list[Math.floor(rand() * list.length)];

const categories = ['computational', 'computational', 'computational', 'logical', 'storage', 'infrastructure', 'transport'];
const kinds = ['calls', 'calls', 'depends-on', 'data-flow', 'reads', 'writes', 'publishes', 'subscribes'];

/** @type {any[]} */
const components = [];
/** @type {any[]} */
const relationships = [];
const pad = (/** @type {number} */ n) => String(n).padStart(2, '0');

for (let g = 0; g < groups; g++) {
  const gid = `domain-${pad(g)}`;
  components.push({ id: gid, name: `Domain ${pad(g)}`, kind: 'subsystem', category: 'logical', purpose: 'Synthetic grouping for the benchmark.', illustrative: true });
  for (let c = 0; c < perGroup; c++) {
    const id = `svc-${pad(g)}-${pad(c)}`;
    components.push({ id, name: `Service ${pad(g)}.${pad(c)}`, category: pick(categories), parent: gid, purpose: 'Synthetic component for the benchmark.', illustrative: true });
  }
}
const leaves = components.filter((c) => c.kind !== 'subsystem');
const seen = new Set();
const connect = (/** @type {any} */ from, /** @type {any} */ to) => {
  if (from.id === to.id) return;
  const kind = pick(kinds);
  const id = `${from.id}-${kind}-${to.id}`;
  if (seen.has(id)) return;
  seen.add(id);
  relationships.push({ id, kind, from: from.id, to: to.id, description: 'Synthetic relationship.' });
};
// Tiered structure, like a service architecture: components sit in one of five
// tiers inside their domain and connect to the next tier; domains sit in one of
// four stages and a few relationships cross to the next stage.
const TIERS = 5;
const STAGES = 4;
const tierOf = (/** @type {number} */ c) => Math.floor((c * TIERS) / perGroup);
for (let g = 0; g < groups; g++) {
  const own = leaves.filter((c) => c.parent === `domain-${pad(g)}`);
  own.forEach((from, i) => {
    const next = own.filter((_, j) => tierOf(j) === tierOf(i) + 1);
    if (!next.length) return;
    const targets = 1 + Math.floor(rand() * 2);
    for (let t = 0; t < targets; t++) connect(from, pick(next));
  });
  const later = leaves.filter((c) => Number(c.parent.slice(-2)) % STAGES === (g % STAGES) + 1);
  if (later.length) for (let x = 0; x < 5; x++) connect(pick(own), pick(later));
}

const spec = {
  exegra: '0.1',
  system: {
    id: 'benchmark',
    name: 'Synthetic benchmark',
    description: `Generated by tools/make-benchmark.js (${groups} subsystems x ${perGroup} components). It describes nothing real and exists to measure rendering and layout.`,
    illustrative: true,
  },
  components,
  relationships,
  claims: [
    { id: 'benchmark-dependencies-acyclic', kind: 'structural', statement: 'The synthetic dependency relationships contain no cycle.', evaluate: { method: 'acyclic' } },
  ],
};

const lines = ['{', '  // Synthetic. Regenerate with: node tools/make-benchmark.js', `  "exegra": ${JSON.stringify(spec.exegra)},`, `  "system": ${JSON.stringify(spec.system)},`, '  "components": ['];
lines.push(components.map((c) => '    ' + JSON.stringify(c)).join(',\n'));
lines.push('  ],', '  "relationships": [');
lines.push(relationships.map((r) => '    ' + JSON.stringify(r)).join(',\n'));
lines.push('  ],', '  "claims": [');
lines.push(spec.claims.map((c) => '    ' + JSON.stringify(c)).join(',\n'));
lines.push('  ]', '}', '');
const text = lines.join('\n');

const check = analyzeSpec(text);
if (check.errorCount) {
  console.error(check.diagnostics.filter((d) => d.severity === 'error').slice(0, 5));
  process.exit(1);
}
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'specs', 'benchmark', 'spec.jsonc');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, text);
console.log(`wrote ${out}: ${components.length} components, ${relationships.length} relationships`);
