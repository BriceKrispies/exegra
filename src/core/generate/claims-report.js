// claims-report.md and claims-report.json: the claim inventory and verification
// report. Statuses come only from the supplied ClaimResults; a claim without a
// result is reported as not evaluated, never as verified.

import { semanticHash } from '../hash.js';
import {
  text, oneLine, cell, list, sourceOf, statusLabel, json, markdown,
} from './manifest.js';

/** @typedef {import('../types.js').Model} Model */
/** @typedef {import('../types.js').Entity} Entity */
/** @typedef {import('../claims.js').ClaimResult} ClaimResult */

/** Summary order of claim statuses (also the order of the summary table). */
export const STATUS_ORDER = ['verified', 'supported', 'violated', 'inconclusive', 'not-evaluated'];

/**
 * One row per claim in declaration order. `result` is the supplied ClaimResult,
 * or a synthesized not-evaluated result when none was supplied.
 * @param {Model} model
 * @param {ClaimResult[]} [claimResults]
 * @returns {{claim: Entity, result: ClaimResult, supplied: boolean}[]}
 */
export function claimRows(model, claimResults = []) {
  const hash = semanticHash(model);
  /** @type {Map<string, ClaimResult>} */
  const byId = new Map();
  for (const r of claimResults) if (!byId.has(r.claimId)) byId.set(r.claimId, r);
  return (model.byKind.claim ?? []).map((claim) => {
    const supplied = byId.get(claim.id);
    return { claim, supplied: supplied !== undefined, result: supplied ?? unevaluated(model, claim, hash) };
  });
}

/**
 * @param {Model} model @param {Entity} claim @param {string} hash
 * @returns {ClaimResult}
 */
function unevaluated(model, claim, hash) {
  const ev = claim.data.evaluate && typeof claim.data.evaluate === 'object' ? claim.data.evaluate : null;
  const evidence = (model.byKind.evidence ?? [])
    .filter((e) => e.data.claim === claim.id)
    .map((e) => ({ id: e.id, kind: text(e.data.kind), ref: text(e.data.ref), supports: e.data.supports !== false, recorded: /** @type {const} */ ('none') }));
  return {
    claimId: claim.id,
    kind: claim.data.kind,
    method: ev && typeof ev.method === 'string' ? ev.method : null,
    status: 'not-evaluated',
    evaluator: 'none',
    semanticHash: hash,
    scope: 'Nothing was checked: no evaluation result was supplied for this claim.',
    explanation: 'No evaluation result was supplied.',
    assumptions: list(claim.data.assumptions).filter((a) => typeof a === 'string'),
    involved: [],
    evidence,
  };
}

/**
 * Count of claims per status, in STATUS_ORDER.
 * @param {{result: ClaimResult}[]} rows
 * @returns {Record<string, number>}
 */
export function summaryCounts(rows) {
  /** @type {Record<string, number>} */
  const counts = {};
  for (const s of STATUS_ORDER) counts[s] = 0;
  for (const { result } of rows) if (Object.hasOwn(counts, result.status)) counts[result.status]++;
  return counts;
}

/** @param {Model} model @param {any} id */
function assumptionStatement(model, id) {
  const a = model.entities.get(id);
  return a ? text(a.data.statement) : '';
}

/**
 * @param {Model} model
 * @param {{claimResults?: ClaimResult[]}} [opts]
 * @returns {string} claims-report.json text
 */
export function generateClaimsReportJson(model, opts = {}) {
  const rows = claimRows(model, opts.claimResults ?? []);
  const summary = { ...summaryCounts(rows), total: rows.length };
  return json({
    format: 'exegra-claims-report',
    version: 1,
    semanticHash: semanticHash(model),
    summary,
    claims: rows.map(({ claim, result }) => ({
      id: claim.id,
      kind: claim.data.kind,
      statement: text(claim.data.statement),
      method: result.method ?? null,
      status: result.status,
      statusLabel: statusLabel(result.status),
      evaluator: result.evaluator,
      scope: result.scope,
      explanation: result.explanation,
      assumptions: (result.assumptions ?? []).map((id) => ({ id, statement: assumptionStatement(model, id) })),
      counterexample: result.counterexample ?? null,
      evidence: result.evidence ?? [],
      subjects: list(claim.data.subjects).filter((s) => typeof s === 'string'),
      source: sourceOf(claim),
    })),
  });
}

/**
 * @param {Model} model
 * @param {{claimResults?: ClaimResult[]}} [opts]
 * @returns {string} claims-report.md text
 */
export function generateClaimsReport(model, opts = {}) {
  const rows = claimRows(model, opts.claimResults ?? []);
  const counts = summaryCounts(rows);
  const L = [];
  L.push(
    '# Claims report', '',
    `Semantic hash: \`${semanticHash(model)}\`. Generated by Exegra from the semantic model. Do not edit; regenerate.`, '',
    '## How to read this report', '',
    'Verified means checked by Exegra against this model revision within the stated scope and assumptions. ' +
    'Supported means resting on external evidence that Exegra did not derive from the model. ' +
    'A declared claim is not thereby true. ' +
    'A simulation of the model is not evidence about deployed software.', '',
    '## Summary', '',
    '| Status | Count |', '| --- | --- |',
    ...STATUS_ORDER.map((s) => `| ${s} | ${counts[s]} |`),
    `| total | ${rows.length} |`, '',
  );

  for (const { claim, result } of rows) {
    L.push(`## ${oneLine(claim.id)}`, '', text(claim.data.statement), '');
    L.push(
      `- Kind: ${oneLine(claim.data.kind)}`,
      `- Method: ${result.method ? oneLine(result.method) : 'none'}`,
      `- **Status**: ${statusLabel(result.status)}`,
      `- Evaluator: ${oneLine(result.evaluator)}`,
      `- Scope: ${oneLine(result.scope)}`,
      `- Explanation: ${oneLine(result.explanation)}`, '',
    );

    L.push('**Holds only if**', '');
    const assumptions = result.assumptions ?? [];
    if (assumptions.length) {
      for (const id of assumptions) {
        const statement = assumptionStatement(model, id);
        L.push(statement ? `- \`${oneLine(id)}\`: ${oneLine(statement)}` : `- \`${oneLine(id)}\``);
      }
      L.push('');
    } else L.push('No assumptions are declared.', '');

    L.push('**Counterexample**', '');
    const ce = result.counterexample;
    if (!ce) L.push('None.', '');
    else {
      L.push(`- Summary: ${oneLine(ce.summary)}`);
      if (list(ce.entities).length) L.push(`- Entities: ${ce.entities.map((id) => `\`${oneLine(id)}\``).join(', ')}`);
      if (list(ce.path).length) L.push(`- Path: ${/** @type {string[]} */ (ce.path).map((p) => oneLine(p)).join(' -> ')}`);
      if (ce.scenario !== undefined) L.push(`- Scenario: ${oneLine(ce.scenario)}`);
      if (typeof ce.stepIndex === 'number') L.push(`- Step: ${ce.stepIndex < 0 ? 'initial configuration' : ce.stepIndex}`);
      L.push('');
    }

    L.push('**Evidence**', '');
    const evidence = result.evidence ?? [];
    if (evidence.length) {
      L.push(
        '| Id | Kind | Ref | Supports | Recorded |', '| --- | --- | --- | --- | --- |',
        ...evidence.map((e) => `| ${cell(e.id)} | ${cell(e.kind)} | ${cell(e.ref)} | ${e.supports === false ? 'contradicts' : 'supports'} | ${cell(e.recorded)} |`),
        '',
      );
    } else L.push('None is attached.', '');
  }

  return markdown(L);
}
