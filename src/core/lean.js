// The call boundary to Exegra's Lean core: formal/ compiled to WebAssembly by
// `npm run build:formal-wasm` (tools/build-formal-wasm.js) into src/engine/lean/.
//
// The module exports one Lean function, Exegra.Api.handle (formal/Exegra/Api.lean): a JSON request
// {"fn": <name>, "args": <JSON>} to a JSON reply {"ok": <result>} or {"error": <message>}. The
// functions are registered on the Lean side (Exegra.Api.registry); this binding knows none of them
// by name, so a module port adds functions without changing this file.
//
//   call(fn, args)          -> {ok: true, value} | {ok: false, error}      (args and value as JS values)
//   callText(fn, argsText)  -> {ok: true, text}  | {ok: false, error}      (JSON text in and out)
//   leanFunctions()         -> [{name, doc}]                               (the registry)
//
// Errors are values: an unknown function, malformed arguments and a refusal by the function come
// back as {ok: false, error}. A trap inside the module (which the Lean code should never cause, for
// example the stack running out) is caught here and also reported as {ok: false, error}; the
// instance is then discarded and the next call starts a fresh one.
//
// Loading. The emscripten glue is built for the web with synchronous instantiation and is handed the
// module bytes. In Node, initLean() and the first call load it synchronously (node:fs, reached through
// process.getBuiltinModule so this module stays importable by the browser bundle unchanged); in a
// browser or worker, initLean() must be awaited before the first call.

/** The emscripten module, as far as this binding uses it. @typedef {{_exegra_init: () => number, _exegra_pointer_size: () => number,
 *  _exegra_request: (p: any, n: any) => void, _exegra_reply_ptr: () => any, _exegra_reply_len: () => any,
 *  _malloc: (n: any) => any, _free: (p: any) => void, HEAPU8: Uint8Array}} LeanModule */
/** @typedef {(arg: Record<string, any>) => Promise<unknown>} Factory */
/** @typedef {{ok: true, value: any} | {ok: false, error: string}} CallResult */
/** @typedef {{ok: true, text: string} | {ok: false, error: string}} CallTextResult */

const WASM_URL = new URL('../engine/lean/exegra-lean.wasm', import.meta.url);
const NOT_BUILT = 'The Lean core is not built: run "npm run build:formal-wasm" (needs elan with the toolchain of formal/lean-toolchain, git and network access for the first build).';

const nodeProcess = typeof process !== 'undefined' && typeof process?.getBuiltinModule === 'function' ? process : null;
const encoder = new TextEncoder();
const decoder = new TextDecoder();

/** @type {{factory: Factory, bytes: Uint8Array}|null} */
let source = null;
/** @type {{m: LeanModule, wide: boolean}|null} */
let instance = null;
/** @type {Promise<void>|null} */
let loading = null;
/** The last lines the module wrote to stderr (Lean panics), reported with a trap. */
let stderr = /** @type {string[]} */ ([]);

function loadSourceInNode() {
  const proc = /** @type {NodeJS.Process} */ (nodeProcess);
  const fs = /** @type {typeof import('node:fs')} */ (proc.getBuiltinModule('node:fs'));
  const { createRequire } = /** @type {typeof import('node:module')} */ (proc.getBuiltinModule('node:module'));
  try {
    const bytes = fs.readFileSync(WASM_URL);
    // The glue is an ES module without top-level await, so require() loads it synchronously.
    const glue = createRequire(import.meta.url)('../engine/lean/exegra-lean.mjs');
    source = { factory: glue.default, bytes };
  } catch (e) {
    throw new Error(`${NOT_BUILT} (${/** @type {Error} */ (e).message})`);
  }
}

async function loadSourceInBrowser() {
  let glue, bytes;
  try {
    // @ts-ignore generated by npm run build:formal-wasm; absent until it is built
    glue = await import('../engine/lean/exegra-lean.mjs');
    const res = await fetch(WASM_URL);
    if (!res.ok) throw new Error(`${WASM_URL.href}: HTTP ${res.status}`);
    bytes = new Uint8Array(await res.arrayBuffer());
  } catch (e) {
    throw new Error(`${NOT_BUILT} (${/** @type {Error} */ (e).message})`);
  }
  source = { factory: glue.default, bytes };
}

/** Instantiate the module from `source`: synchronous, because the glue compiles synchronously. */
function instantiate() {
  const src = /** @type {{factory: Factory, bytes: Uint8Array}} */ (source);
  /** @type {any} */
  const m = {
    wasmBinary: src.bytes,
    print: () => {},
    printErr: (/** @type {string} */ line) => { stderr = [...stderr.slice(-9), line]; },
  };
  // The factory returns a promise, but with synchronous compilation the module is ready on return.
  src.factory(m).catch(() => {});
  if (typeof m._exegra_init !== 'function') throw new Error(`The Lean core could not be instantiated. ${stderr.join(' ')}`.trim());
  if (m._exegra_init() !== 0) throw new Error(`The Lean core failed to initialize. ${stderr.join(' ')}`.trim());
  instance = { m, wide: m._exegra_pointer_size() === 8 };
}

/**
 * Load the Lean core. In Node the work is done before this returns (the promise is already settled);
 * in a browser or worker the returned promise must be awaited. Calling it again is harmless.
 * @returns {Promise<void>}
 */
export function initLean() {
  if (instance) return Promise.resolve();
  if (source) {
    instantiate();
    return Promise.resolve();
  }
  if (nodeProcess) {
    loadSourceInNode();
    instantiate();
    return Promise.resolve();
  }
  loading ??= loadSourceInBrowser().then(instantiate).catch((e) => {
    loading = null;
    throw e;
  });
  return loading;
}

/** Whether the Lean core is loaded and calls can be made. */
export function leanReady() {
  return instance !== null;
}

/**
 * Send one request text and return the reply text. Throws only when the core cannot be loaded.
 * @param {string} request
 * @returns {string}
 */
function exchange(request) {
  if (!instance) {
    if (source || nodeProcess) initLean();
    else throw new Error('The Lean core is not loaded yet: await initLean() first.');
  }
  const { m, wide } = /** @type {{m: LeanModule, wide: boolean}} */ (instance);
  const ptr = (/** @type {number} */ n) => (wide ? BigInt(n) : n);
  const bytes = encoder.encode(request);
  try {
    const p = Number(m._malloc(ptr(bytes.length + 1)));
    m.HEAPU8.set(bytes, p);
    try {
      m._exegra_request(ptr(p), ptr(bytes.length));
    } finally {
      m._free(ptr(p));
    }
    const rp = Number(m._exegra_reply_ptr());
    const rl = Number(m._exegra_reply_len());
    return decoder.decode(m.HEAPU8.subarray(rp, rp + rl));
  } catch (e) {
    // A trap leaves the instance in an unknown state: drop it; the next call instantiates again.
    instance = null;
    const msg = e instanceof Error ? e.message : String(e);
    return JSON.stringify({ error: `the Lean core trapped: ${msg}${stderr.length ? ` (${stderr.join(' ')})` : ''}` });
  }
}

const OK = '{"ok":';

/**
 * Stand-ins for registered Lean functions, by name: a test replaces one function at this boundary (for example
 * `claims.status`, to show that no status is computed in JavaScript) without building another Lean core.
 * @type {Map<string, (args: any) => any>}
 */
const overrides = new Map();

/**
 * Replace the Lean function `fn` with `impl` until the returned function is called. `impl` takes the arguments
 * as a JS value and returns the result as a JS value (or throws, which is reported as an error reply).
 * @param {string} fn @param {(args: any) => any} impl
 * @returns {() => void} restores the Lean function
 */
export function overrideLeanFunction(fn, impl) {
  overrides.set(fn, impl);
  return () => { if (overrides.get(fn) === impl) overrides.delete(fn); };
}

/**
 * Call a registered Lean function with arguments given as JSON text; the result comes back as JSON
 * text, unparsed.
 * @param {string} fn
 * @param {string} argsText
 * @returns {CallTextResult}
 */
export function callText(fn, argsText) {
  const stand = overrides.get(fn);
  if (stand) {
    try {
      return { ok: true, text: JSON.stringify(stand(JSON.parse(argsText))) };
    } catch (e) {
      return { ok: false, error: e instanceof Error ? e.message : String(e) };
    }
  }
  const reply = exchange(`{"fn":${JSON.stringify(fn)},"args":${argsText}}`);
  if (reply.startsWith(OK)) return { ok: true, text: reply.slice(OK.length, -1) };
  try {
    const parsed = JSON.parse(reply);
    return { ok: false, error: typeof parsed.error === 'string' ? parsed.error : `unexpected reply: ${reply.slice(0, 200)}` };
  } catch {
    return { ok: false, error: `unexpected reply: ${reply.slice(0, 200)}` };
  }
}

/**
 * Call a registered Lean function.
 * @param {string} fn
 * @param {any} [args]
 * @returns {CallResult}
 */
export function call(fn, args = null) {
  const r = callText(fn, JSON.stringify(args ?? null));
  return r.ok ? { ok: true, value: JSON.parse(r.text) } : r;
}

/** The functions the Lean core registers, in lookup order. @returns {{name: string, doc: string}[]} */
export function leanFunctions() {
  const r = call('api.functions');
  if (!r.ok) throw new Error(r.error);
  return r.value;
}
